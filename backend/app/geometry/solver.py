"""Geometry Solver foundation: turns an `ArchitecturalSpec` (room types, counts, relationships,
zones, circulation) plus a `BuildingFootprintSpec` — NEVER a `SiteSpec`, see that class's docstring —
into concrete, non-overlapping, in-bounds room instances. Every HARD constraint is enforced exactly;
SOFT relationships/zones/circulation are treated as an objective to maximize among the valid layouts
found, never as something that can silently fail.

Algorithm (bounded backtracking over "corner point" candidate positions, run once per instance-order
strategy and pooled — see Step 3 below):

1. Order instances: the circulation entry room always first; then, per `_INSTANCE_ORDER_STRATEGIES`,
   either by how many HARD relationships its type has (most-constrained-first — the original, default
   CSP ordering heuristic), by largest target area first, or by smallest target area first (both
   standard rectangle-packing heuristics). The search below runs once per strategy.
2. For each instance, generate a small set of candidate (width, height) shapes from
   `target_area_m2` (preference, tried first) and `min_area_m2`/`max_area_m2` (hard bounds, tried as
   fallback areas), each combined with a few fixed aspect ratios, filtered to respect the HARD
   `min_width_m` on both sides.
3. Positions tried are the footprint origin plus every "corner point" generated by already-placed
   rooms (flush against a placed room's right or bottom edge — a standard rectangle-packing
   heuristic).
4. A candidate placement is accepted only if it stays inside the footprint boundary and does not
   overlap any already-placed room; the search backtracks otherwise.
5. Once every instance is placed, the COMPLETE layout is checked against every HARD requirement (see
   `_layout_satisfies_hard_requirements`): relationships, the footprint's `available_area_m2` budget,
   the entry room touching the footprint perimeter, and any zone whose `cohesion_severity="hard"`.
   Failing any of these rejects the complete layout and the search backtracks further. This two-phase
   check (fast per-step feasibility, then mandatory final verification) is what makes the search
   correct.
6. Every complete valid layout found across ALL strategy passes (up to `_MAX_SOLUTIONS` each,
   deduplicated by exact geometry) is pooled and scored by `_score_candidate`: soft relationships
   satisfied + zone cohesion + circulation reach (as before this milestone) PLUS three new, explicitly
   weighted geometric terms — footprint utilization, compactness, and unused-space fragmentation (see
   `app/geometry/quality.py` and the `_WEIGHT_*` constants below). The highest-scoring pooled candidate
   is returned as `GeometrySolverResult(status=satisfied, ...)`, along with the runner-ups' own score
   breakdowns (`candidate_summaries`) so the choice is explainable, not just a single opaque number. If
   no valid layout is found in any pass, `GeometrySolverResult(status=unsatisfiable, ...)` is returned
   instead — the solver never raises for this expected outcome, and never returns a partial layout.

--- V1 approximations, documented explicitly rather than silently assumed ---

**Adjacency vs. direct access**: both come from the same real quantity — `_shared_edge_length`, the
length in meters of the wall segment two rooms actually share. `adjacent` only requires that length to
be positive; `direct_access` requires it to be at least `_DOOR_OPENING_MIN_M` (a standard interior door
width). No door/opening is actually modeled or drawn. Satisfying `direct_access` proves "a door could
plausibly fit in this wall," never that one exists — every `ConstraintCheckResult` for a satisfied
`direct_access` relationship carries a `note` saying exactly this, so nothing downstream mistakes the
proxy for a real opening.

**Zone cohesion**: a zone's soft "compactness" score is the count of same-zone room PAIRS that end up
adjacent — a simple, deterministic proxy for "grouped together," not a measure of enclosure, shared
corridor, or travel distance. A `cohesion_severity="hard"` zone additionally requires its rooms to form
one connected component via adjacency (every room reachable from every other through same-zone
neighbors) — still just a connectivity graph over shared walls, not a verified walkable path.

**Circulation**: `entry_room_type` is enforced as a HARD requirement that at least one instance of
that type touches one of the footprint's ALLOWED entry edges (`BuildingFootprintSpec.
allowed_entry_edges` — all four edges if unset; candidate placement generation offers all four
footprint corners, so any single edge is genuinely reachable) — approximating "could plausibly have a
front door on a permitted side," not a verified accessible approach from a real street/path (which this
codebase has no data for yet; see Feature 03's location-resolution gap). `requires_hallway` does NOT
create or reserve any hallway polygon. Instead, when true, a SOFT "circulation reach" score rewards
every non-entry-type room that is directly adjacent to an entry-room-type instance — a deliberately
crude proxy for "not obviously buried behind another unrelated room," since a real answer requires an
actual circulation graph/path-planning this foundation does not implement. A high reach score does NOT
prove every room is genuinely reachable without crossing another private room; it only makes such
layouts score better than deeply nested alternatives when multiple valid layouts exist.

This is intentionally a real, verifiable constraint search, not a fixed heuristic layout — but it is
still a "foundation." Swapping in a stronger solver (e.g. an ILP/CP-SAT backend, or a real circulation
graph) later only needs to satisfy this module's function signature.

**Pre-solver contradiction check**: before any search starts, `_find_pre_solver_contradiction` looks
for a small, fixed set of deterministic, easy-to-prove-impossible combinations (a HARD adjacency and a
HARD separation on the same type pair; a HARD direct_access and a HARD separation on the same pair; an
inconsistent min/max area on a program item; a min_width_m that exceeds both footprint dimensions; a
room type referenced but missing from the program). Finding one short-circuits straight to
`status=unsatisfiable` with a specific reason, skipping the search entirely. This is deliberately NOT a
general constraint-satisfiability prover — it only catches contradictions cheap and safe to detect
outright; anything subtler still goes through the full backtracking search and may still come back
unsatisfiable there instead.
"""

